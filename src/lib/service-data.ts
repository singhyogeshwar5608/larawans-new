export function getServiceBySlug(slug: string): ServiceDetail | undefined {
  if (!slug) return undefined;
  const cleanSlug = decodeURIComponent(slug).toLowerCase().trim().replace(/\/$/, "");

  const direct = ALL_SERVICES_DETAILS.find((s) => s.slug.toLowerCase() === cleanSlug);
  if (direct) return direct;

  return ALL_SERVICES_DETAILS.find((s) => {
    const titleSlug = s.title
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/(^-|-$)/g, "");
    return titleSlug === cleanSlug;
  });
}
